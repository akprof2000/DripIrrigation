// telegram.h 🤖💬 Заголовочный файл модуля Telegram бота (FastBot2)
#ifndef _TELEGRAM_h
#define _TELEGRAM_h

#include <Arduino.h>
#include "botutil.h"  // 🧰 IntWith2Zero и др. (исторически объявлялись здесь)

// 🚀 Инициализация Telegram бота (FastBot2): подключение обработчика, загрузка пользователей
void botInit();

// 💾 Отправить уведомление об отключении SD-карты всем пользователям
void dropCDCard();

// 💾 Отправить уведомление о подключении SD-карты всем пользователям
void connectCDCard();

// 📨 Отправить статусное сообщение всем подписанным пользователям
void sendStatus(String text);

// 🔌 Контроль связи с Telegram: подключить детект (в botInit)
void botMonitorAttach();
// 🔌 Тик контроля связи (в ReCheck). gotUpdate = результат bot.tick()
void botMonitorTick(bool gotUpdate);

// 🔄 Проверить необходимость обновления конфигурации на SD-карте
bool telegramNeedUpdate();

// 📮 Запомнить в EEPROM позицию в очереди Telegram (следующий ожидаемый
//    update_id). Вызывать ПЕРЕД любой перезагрузкой, иначе после старта
//    прилетит уже обработанное сообщение — например, файл прошивки, и
//    обновление зациклится.
void telegramSaveUpdateOffset();

// 🆘 Разослать отчёт об аппаратных авариях всем пользователям (один раз на
//    поломку). Вызывать после botInit и из loop — на случай, если в момент
//    старта связи ещё не было.
void hwReportToChat();

// 🗜️ Тик отложенного OTA из сжатого .gz — вызывать в loop() (вне колбэка tick).
//     Скачивает архив, распаковывает gzip на лету и прошивает.
void telegramGzOtaTick();

// 🔧 Идёт ли у кого-нибудь диалог калибровки или поиска датчика.
// В эти моменты датчик держат в воде / на воздухе, поэтому показания нерабочие —
// авто-расширение границ калибровки должно быть отключено.
bool calibrationInProgress();

#endif
