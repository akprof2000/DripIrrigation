// faults.h 🩺 Реестр аппаратных неисправностей
//
// Зачем: раньше отсутствие RTC или SD-карты вешало прошивку в бесконечном
// while ещё до старта loop(). Бот не поднимался, сообщений в чат не было, и
// причину можно было узнать, только подключившись к устройству кабелем.
//
// Теперь каждая плата инициализируется неблокирующе: несколько попыток, и если
// железо не ответило — факт записывается сюда, а загрузка продолжается. Бот
// поднимается всегда и сообщает список неисправностей в чат, а его интерфейс
// переходит в аварийный режим — остаётся одна кнопка перезагрузки.
#pragma once

#include <Arduino.h>

// 🔧 Аппаратные узлы, состояние которых отслеживается при старте.
enum HwId : uint8_t {
  HW_RTC = 0,   // 🕐 Часы реального времени DS3231 (шина I2C)
  HW_SD,        // 💾 SD-карта: конфигурация и журналы
  HW_VALVES,    // 🚰 Расширитель портов PCF8574: клапаны
  HW_COUNT
};

// ❌ Отметить узел неисправным. detail — короткая причина для чата
//    («не отвечает на шине I2C»), она попадает в отчёт как есть.
void hwSetFault(HwId id, const char* detail);

// ✅ Отметить узел исправным (узел восстановился — например, вернули карту).
void hwSetOk(HwId id);

// 🔍 Неисправен ли конкретный узел.
bool hwFaulty(HwId id);

// 🆘 Есть ли хоть одна неисправность. Это и есть признак аварийного режима:
//    полив остановлен, интерфейс бота свёрнут до кнопки перезагрузки.
bool hwHasFault();

// 📋 Отчёт для чата: заголовок, список неисправных узлов с причинами и
//    указание, что делать. Формат HTML — как остальные сообщения бота.
String hwFaultReport();

// 🏷️ Короткая строка для заголовка меню: «RTC, SD-карта».
String hwFaultShort();

// 📨 Отправлен ли отчёт об авариях в чат (чтобы не слать его повторно).
bool hwReportSent();
void hwMarkReportSent();
